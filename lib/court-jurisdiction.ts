export function normalizeAdminRegion(value: string | undefined): AdminRegion | "" {
  if (!value) return "";
  const exact = ADMIN_REGIONS.find((r) => r === value);
  if (exact) return exact;

  const aliases: Array<[string[], AdminRegion]> = [
    [["서울"], "서울특별시"],
    [["부산"], "부산광역시"],
    [["대구"], "대구광역시"],
    [["인천"], "인천광역시"],
    [["광주"], "광주광역시"],
    [["대전"], "대전광역시"],
    [["울산"], "울산광역시"],
    [["세종"], "세종특별자치시"],
    [["경기"], "경기도"],
    [["강원"], "강원특별자치도"],
    [["충북", "충청북"], "충청북도"],
    [["충남", "충청남"], "충청남도"],
    [["전북", "전라북"], "전북특별자치도"],
    [["전남", "전라남"], "전라남도"],
    [["경북", "경상북"], "경상북도"],
    [["경남", "경상남"], "경상남도"],
    [["제주"], "제주특별자치도"],
  ];
  for (const [keys, region] of aliases) {
    if (keys.some((key) => value.includes(key))) return region;
  }
  return "";
}

export function courtsForRegion(value: string | undefined): readonly string[] {
  const region = normalizeAdminRegion(value);
  return region ? REGION_COURT_OPTIONS[region] : [];
}
